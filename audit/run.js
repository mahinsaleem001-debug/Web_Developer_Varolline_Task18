import fs from 'node:fs';
import { attacks, runAttack } from './attacks.js';

const rows = [];
for (const a of attacks) {
  const before = await runAttack(a, a.flags);
  const after = await runAttack(a, []);
  rows.push({ a, before, after });
  console.log(`${a.id.padEnd(4)} before: ${before.exploited ? 'EXPLOITED' : 'blocked  '}  after: ${after.exploited ? 'EXPLOITED' : 'blocked  '}  ${a.name}`);
}

const esc = (s) => String(s).replace(/\|/g, '\\|');
let md = '# Audit results\n\nGenerated by `npm run audit`. "Before" runs the build with that one weakness switched on. "After" runs the normal build.\n\n';
md += '| # | Category | Attack | Before the fix | After the fix | Fix |\n|---|---|---|---|---|---|\n';
for (const { a, before, after } of rows) {
  md += `| ${a.id} | ${a.category} | ${esc(a.name)} | **Exploited**: ${esc(before.evidence)} | **Blocked**: ${esc(after.evidence)} | ${esc(a.fix)} |\n`;
}
fs.writeFileSync(new URL('./RESULTS.md', import.meta.url), md);

const bad = rows.filter((r) => !r.before.exploited || r.after.exploited);
console.log(`\n${rows.length} attacks. ${rows.length - bad.length} behave as expected (exploited before, blocked after).`);
if (bad.length) { console.log('Unexpected:', bad.map((r) => r.a.id).join(', ')); process.exit(1); }
